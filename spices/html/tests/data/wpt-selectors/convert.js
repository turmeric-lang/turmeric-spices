// convert.js -- selectors.js (WPT) -> selectors.tsv for tests/select.tur.
//
//   node convert.js > selectors.tsv
//
// One line per selector: kind (valid/invalid), the selector, the expected ids
// (space-separated, tree order), the contexts it excludes (comma-separated)
// and, for a selector this engine rejects on purpose, why.  Tab, newline, CR
// and backslash in a field are written \t \n \r \\.
const fs = require("fs");
const src = fs.readFileSync(__dirname + "/selectors.js", "utf8");
const { validSelectors, invalidSelectors, TEST_QSA } =
  new Function(src + "; return {validSelectors, invalidSelectors, TEST_QSA};")();
const esc = s => String(s).replace(/\\/g, "\\\\").replace(/\t/g, "\\t")
                          .replace(/\n/g, "\\n").replace(/\r/g, "\\r");
// Pseudo-classes dom/select rejects with a compile error (a static tree has
// no link, focus, form or target state; :lang needs inheritance).
const rejected = [
  ["link", "dynamic state"], ["visited", "dynamic state"], ["target", "dynamic state"],
  ["hover", "dynamic state"], ["active", "dynamic state"], ["focus", "dynamic state"],
  ["checked", "UI state"], ["enabled", "UI state"], ["disabled", "UI state"],
  ["indeterminate", "UI state"], ["default", "UI state"], ["lang", "inherited state"],
  ["dir", "inherited state"], ["before", "pseudo-element"], ["after", "pseudo-element"],
  ["first-line", "pseudo-element"], ["first-letter", "pseudo-element"],
  ["slotted", "pseudo-element"],
];
function why(sel) {
  for (const [p, r] of rejected)
    if (new RegExp(":" + p + "(?![-\\w])", "i").test(sel)) return r + " (:" + p + ")";
  return "";
}
const out = ["# generated by convert.js from selectors.js; do not edit"];
for (const s of invalidSelectors)
  out.push(["invalid", esc(s.selector), "", "", ""].join("\t"));
for (const s of validSelectors) {
  if (!(s.testType & TEST_QSA)) continue;
  out.push(["valid", esc(s.selector), (s.expect || []).join(" "),
            (s.exclude || []).join(","), why(s.selector)].join("\t"));
}
process.stdout.write(out.join("\n") + "\n");
